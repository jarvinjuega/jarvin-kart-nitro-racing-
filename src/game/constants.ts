const SAVE_STORAGE_KEY = 'jarvin_kart_turbo_save_v1';
const CONTROLS_STORAGE_KEY = 'jarvin_kart_turbo_controls_v1';

export function detectMobileClient(): boolean {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') return false;
  return (
    /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent) ||
    (window.matchMedia?.('(pointer: coarse)')?.matches && window.innerWidth < 1024)
  );
}

export function loadSaveProgress(): SaveProgress {
  const defaultUnlocked = [...BASE_PLAYABLE_CHARACTER_IDS];
  const isMobile = detectMobileClient();
  const isStandalone =
    typeof window !== 'undefined' &&
    Boolean(window.matchMedia?.('(display-mode: standalone)')?.matches || (navigator as unknown as { standalone?: boolean }).standalone);
  if (!isMobile) {
    defaultUnlocked.push('pc_gamer');
  }
  if (isStandalone) {
    defaultUnlocked.push('celular_kart');
  }
  const fallback: SaveProgress = {
    unlockedChapters: 1,
    adventureCompletedTracks: [],
    jarvinExeCutsceneSeen: false,
    defeatedBosses: [],
    unlockedCharacters: defaultUnlocked,
    relicKeys: {},
    battleUnlocked: false,
    specialModesUnlocked: {
      madness: false,
      elimination: false,
      tokens: false,
      eightPlayerPc: false,
    },
    collectedTokenTracks: [],
    appDownloadedUnlocked: isStandalone,
    playerNickname: 'Corredor',
    bestTimes: {},
    bestRelicTimes: {},
    bestGhosts: {},
    sfxVolume: 0.7,
    musicEnabled: true,
    graphicsMode: 'optimized',
    audioMode: 'stereo',
    touchControls: 'auto',
  };
  try {
    const raw = localStorage.getItem(SAVE_STORAGE_KEY);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw) as Partial<SaveProgress>;
    const relicKeys = parsed.relicKeys ?? {};
    const hasMetalOrGold = Object.values(relicKeys).some((k) => k === 'gold' || k === 'metal');
    const defeatedBosses = Array.isArray(parsed.defeatedBosses) ? parsed.defeatedBosses : [];
    const savedUnlocked = Array.isArray(parsed.unlockedCharacters) ? parsed.unlockedCharacters : [];
    const unlockedSet = new Set<PlayableCharacterId>([...defaultUnlocked, ...savedUnlocked]);
    if (defeatedBosses.includes('jarvin_exe')) {
      unlockedSet.add('jarvin_exe');
    }
    const appDownloadedUnlocked = Boolean(parsed.appDownloadedUnlocked || isStandalone);
    if (appDownloadedUnlocked) {
      unlockedSet.add('celular_kart');
      unlockedSet.add('pc_gamer');
    }
    const collectedTokenTracks = Array.isArray(parsed.collectedTokenTracks) ? parsed.collectedTokenTracks : [];
    const sm = parsed.specialModesUnlocked ?? {
      madness: false,
      elimination: false,
      tokens: false,
      eightPlayerPc: false,
    };
    const eightPlayerPc = Boolean(sm.eightPlayerPc || collectedTokenTracks.length > 0);
    return {
      unlockedChapters: Math.max(1, Math.min(TRACKS.length, parsed.unlockedChapters ?? 1)),
      adventureCompletedTracks: Array.isArray(parsed.adventureCompletedTracks)
        ? parsed.adventureCompletedTracks
        : [],
      jarvinExeCutsceneSeen: Boolean(parsed.jarvinExeCutsceneSeen),
      defeatedBosses,
      unlockedCharacters: Array.from(unlockedSet),
      relicKeys,
      battleUnlocked: Boolean(parsed.battleUnlocked || hasMetalOrGold),
      specialModesUnlocked: {
        madness: Boolean(sm.madness),
        elimination: Boolean(sm.elimination),
        tokens: Boolean(sm.tokens),
        eightPlayerPc,
      },
      collectedTokenTracks,
      appDownloadedUnlocked,
      playerNickname: typeof parsed.playerNickname === 'string' && parsed.playerNickname.trim()
        ? parsed.playerNickname.trim().slice(0, 20)
        : 'Corredor',
      bestTimes: parsed.bestTimes ?? {},
      bestRelicTimes: parsed.bestRelicTimes ?? {},
      bestGhosts: parsed.bestGhosts ?? {},
      sfxVolume: typeof parsed.sfxVolume === 'number' ? parsed.sfxVolume : 0.7,
      musicEnabled: parsed.musicEnabled ?? true,
      graphicsMode: parsed.graphicsMode === 'ps1' ? 'ps1' : 'optimized',
      audioMode: parsed.audioMode === 'mono' ? 'mono' : 'stereo',
      touchControls:
        parsed.touchControls === 'on' || parsed.touchControls === 'off'
          ? parsed.touchControls
          : 'auto',
    };
  } catch {
    return fallback;
  }
}

export function persistSaveProgress(save: SaveProgress): void {
  try {
    localStorage.setItem(SAVE_STORAGE_KEY, JSON.stringify(save));
  } catch {
    // Ignore storage quota errors
  }
}

export function loadControlConfigs(): PlayerControlConfig[] {
  try {
    const raw = localStorage.getItem(CONTROLS_STORAGE_KEY);
    if (!raw) return structuredClone(DEFAULT_CONTROLS);
    const parsed = JSON.parse(raw) as PlayerControlConfig[];
    if (!Array.isArray(parsed) || parsed.length < 4) {
      return structuredClone(DEFAULT_CONTROLS);
    }
    const merged = structuredClone(DEFAULT_CONTROLS);
    for (let i = 0; i < Math.min(8, parsed.length); i++) {
      if (parsed[i] && typeof parsed[i].playerIndex === 'number') {
        merged[i] = parsed[i];
      }
    }
    return merged;
  } catch {
    return structuredClone(DEFAULT_CONTROLS);
  }
}

export function persistControlConfigs(configs: PlayerControlConfig[]): void {
  try {
    localStorage.setItem(CONTROLS_STORAGE_KEY, JSON.stringify(configs));
  } catch {
    // Ignore
  }
}

export function formatRaceTime(ms: number): string {
  if (!Number.isFinite(ms) || ms <= 0) return '00:00.00';
  const totalSeconds = ms / 1000;
  const mins = Math.floor(totalSeconds / 60);
  const secs = Math.floor(totalSeconds % 60);
  const hundredths = Math.floor((ms % 1000) / 10);
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}.${String(hundredths).padStart(2, '0')}`;
}

export function formatKeyCode(code: string): string {
  if (code === 'ShiftLeft') return 'Shift Izq';
  if (code === 'ShiftRight') return 'Shift Der';
  if (code === 'ControlRight') return 'Ctrl Der';
  if (code === 'NumpadEnter') return 'Intro Num';
  if (code === 'Space') return 'Espacio';
  if (code === 'ArrowUp') return 'Flecha ↑';
  if (code === 'ArrowDown') return 'Flecha ↓';
  if (code === 'ArrowLeft') return 'Flecha ←';
  if (code === 'ArrowRight') return 'Flecha →';
  if (code.startsWith('Key')) return code.slice(3);
  if (code.startsWith('Numpad')) return `Num ${code.slice(6)}`;
  return code;
}
