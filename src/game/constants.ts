export const RELIC_TIME_THRESHOLDS_MS = {
  gold: 59000,   // <= 00:59.00 -> Llave de Oro
  metal: 80000,  // <= 01:20.00 (~1 minuto) -> Llave de Metal / Plata (desbloquea Modo Batalla!)
  copper: 140000, // <= 02:20.00 -> Llave de Cobre
};

export function evaluateRelicKey(timeMs: number): RelicKeyTier | null {
  if (!Number.isFinite(timeMs) || timeMs <= 0) return null;
  if (timeMs <= RELIC_TIME_THRESHOLDS_MS.gold) return 'gold';
  if (timeMs <= RELIC_TIME_THRESHOLDS_MS.metal) return 'metal';
  if (timeMs <= RELIC_TIME_THRESHOLDS_MS.copper) return 'copper';
  return null;
}

